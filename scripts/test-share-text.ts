import { exitPhrase, perfectOneIn, resultGrid, runLink, shareText, xLength } from "../src/lib/share-text";
import { dailyNumber } from "../src/lib/daily";
import type { Campaign, MatchResult } from "../src/lib/sim";
let fails = 0;
const t = (n: string, c: boolean) => { console.log((c ? "PASS " : "FAIL ") + n); if (!c) fails++; };
const mk = (o: string, extra: Partial<Campaign> = {}): Campaign => {
  const results = [...o].map((x, i) => ({ round: `R${i}`, opponent: "X", gf: 1, ga: 0, outcome: x as MatchResult["outcome"] }));
  const won = [...o].filter((x) => x === "W").length, drawn = [...o].filter((x) => x === "D").length;
  return { results, won, drawn, lost: o.length - won - drawn, points: 0, eliminatedIn: null, champion: false, perfect: false, ...extra } as Campaign;
};
const O = "https://ucl17-0.com";
const perfect = mk("W".repeat(17), { champion: true, perfect: true });
const near = mk("W".repeat(16) + "L", { eliminatedIn: "Final" });
const mid = mk("WWDWLWWWWWLL", { eliminatedIn: "Quarter-Final" });
const bad = mk("LWLDLLWL", { eliminatedIn: "League Phase" });
const A = shareText({ campaign: perfect, challengeCode: "abc", origin: O });
const B = shareText({ campaign: near, challengeCode: "abc", origin: O });
const C = shareText({ campaign: mid, challengeCode: "abc", origin: O });
const Cb = shareText({ campaign: bad, challengeCode: "abc", origin: O });
const D = shareText({ campaign: mid, dailyNumber: 6, origin: O });
for (const [k, v] of Object.entries({ A, B, C, Cb, D })) console.log(`--- ${k} (X length ${xLength(v.full)})\n${v.full}`);
t("rarity from sim-stats greedy 0.39% -> 1 in 250", perfectOneIn() === 250 && perfectOneIn(1.23) === 100 && perfectOneIn(0.03) === 3350);
t("A verbatim", A.full === `I went 17-0 in 17-0 Draft 🏆\n${"✅".repeat(17)}\nIn our sims only about 1 in 250 runs do that. Think you can?\n${O}/draft?c=abc`);
t("B verbatim", B.body === `16-0-1 in 17-0 Draft. One game off perfect 😩\n${"✅".repeat(16)}❌\nThink you can go 17-0?`);
t("C verbatim", C.body === "8-1-3 in 17-0 Draft, out in the QF\n✅✅🟨✅❌✅✅✅✅✅❌❌\nThink you can go 17-0?");
t("C bad run", Cb.body.startsWith("2-1-5 in 17-0 Draft, out in the league phase\n❌✅❌🟨❌❌✅❌\n"));
t("D verbatim + daily link", D.full === `17-0 Daily #6: 8-1-3\n✅✅🟨✅❌✅✅✅✅✅❌❌\nSame legends for everyone today. Can you beat it?\n${O}/daily`);
t("rarity only on A", ![B, C, Cb, D].some((x) => x.full.includes("in our sims")));
t("no hashtags, no 'odds'", ![A, B, C, Cb, D].some((x) => /#[A-Za-z]|\bodds\b/i.test(x.full)));
t("all well under 280 X chars (longest = A, 148)", [A, B, C, Cb, D].every((x) => xLength(x.full) <= 160));
t("grid = one per match", resultGrid(bad) === "❌✅❌🟨❌❌✅❌");
t("exit champion", exitPhrase({ champion: true, eliminatedIn: null }) === "champions");
t("link fallback", runLink({ origin: O }) === `${O}/draft`);
t("daily #1 = 11 Oct", dailyNumber("2026-10-11") === 1 && dailyNumber("2026-10-16") === 6);
process.exit(fails ? 1 : 0);
