import { exitPhrase, perfectOneIn, resultGrid, runLink, shareText, xLength } from "../src/lib/share-text";
import { dailyNumber } from "../src/lib/daily";
import { pointsLine, recordHeadline, recordWDL, recordWords } from "../src/lib/record";
import type { Campaign, MatchResult } from "../src/lib/sim";
let fails = 0;
const t = (n: string, c: boolean) => { console.log((c ? "PASS " : "FAIL ") + n); if (!c) fails++; };
const mk = (o: string, extra: Partial<Campaign> = {}): Campaign => {
  const results = [...o].map((x, i) => ({ round: `R${i}`, opponent: "X", gf: 1, ga: 0, outcome: x as MatchResult["outcome"] }));
  const won = [...o].filter((x) => x === "W").length, drawn = [...o].filter((x) => x === "D").length;
  return { results, won, drawn, lost: o.length - won - drawn, points: 0, eliminatedIn: null, champion: false, perfect: false, ...extra } as Campaign;
};
const O = "https://ucl17-0.com";
const perfect = mk("W".repeat(17), { champion: true, perfect: true });
const near = mk("W".repeat(16) + "L", { eliminatedIn: "Final" });
const mid = mk("WWDWLWWWWWLL", { eliminatedIn: "Quarter-Final" });
const bad = mk("LWLDLLWL", { eliminatedIn: "League Phase" });
const A = shareText({ campaign: perfect, challengeCode: "abc", origin: O });
const B = shareText({ campaign: near, challengeCode: "abc", origin: O });
const C = shareText({ campaign: mid, challengeCode: "abc", origin: O });
const Cb = shareText({ campaign: bad, challengeCode: "abc", origin: O });
const D = shareText({ campaign: mid, dailyNumber: 6, origin: O });
for (const [k, v] of Object.entries({ A, B, C, Cb, D })) console.log(`--- ${k} (X length ${xLength(v.full)})\n${v.full}`);
t("rarity from sim-stats greedy 0.39% -> 1 in 250", perfectOneIn() === 250 && perfectOneIn(1.23) === 100 && perfectOneIn(0.03) === 3350);
t("A verbatim", A.full === `I went 17-0 in 17-0 Draft 🏆\n${"✅".repeat(17)}\nIn our sims only about 1 in 250 runs do that. Think you can?\n${O}/r/abc`);
t("B verbatim", B.body === `16W 0D 1L in 17-0 Draft. One game off perfect 😩\n${"✅".repeat(16)}❌\nThink you can go 17-0?`);
t("C verbatim", C.body === "8W 1D 3L in 17-0 Draft, out in the QF\n✅✅🟨✅❌✅✅✅✅✅❌❌\nThink you can go 17-0?");
t("C bad run", Cb.body.startsWith("2W 1D 5L in 17-0 Draft, out in the league phase\n❌✅❌🟨❌❌✅❌\n"));
t("D verbatim + daily link", D.full === `17-0 Daily #6: 8W 1D 3L\n✅✅🟨✅❌✅✅✅✅✅❌❌\nSame first picks for everyone today. Can you beat it?\n${O}/daily`);
t("rarity only on A", ![B, C, Cb, D].some((x) => x.full.includes("in our sims")));
t("no hashtags, no 'odds'", ![A, B, C, Cb, D].some((x) => /#[A-Za-z]|\bodds\b/i.test(x.full)));
t("all well under 280 X chars (longest = A, 148)", [A, B, C, Cb, D].every((x) => xLength(x.full) <= 160));
t("grid = one per match", resultGrid(bad) === "❌✅❌🟨❌❌✅❌");
t("exit champion", exitPhrase({ champion: true, eliminatedIn: null }) === "champions");
t("link fallback", runLink({ origin: O }) === `${O}/draft`);
t("daily #1 = 11 Oct", dailyNumber("2026-10-11") === 1 && dailyNumber("2026-10-16") === 6);
// Readable record (copy-final.md #3)
t("recordWDL keeps zeros", recordWDL({ won: 11, drawn: 0, lost: 1 }) === "11W 0D 1L" && recordWDL({ won: 0, drawn: 0, lost: 8 }) === "0W 0D 8L");
t("perfect headline stays 17-0", recordHeadline({ won: 17, drawn: 0, lost: 0 }) === "17-0" && recordHeadline({ won: 11, drawn: 0, lost: 1 }) === "11W 0D 1L");
t("record words", recordWords({ won: 11, drawn: 0, lost: 1 }) === "11 won · 0 drawn · 1 lost");
const lp = (pts: number, n = 8) => pointsLine({ points: pts, results: Array.from({ length: n }, (_, i) => ({ round: `League Phase ${i + 1}` })) });
t("points line", lp(24) === "24 pts in the league phase" && lp(1) === "1 pt in the league phase" && lp(0) === "0 pts in the league phase");
t("points line hidden before the league phase ends", lp(9, 7) === null);
const xl = [A, B, C, Cb, D].map((x) => xLength(x.full));
const worstB = shareText({ campaign: mk("W".repeat(16) + "L", { eliminatedIn: "Final" }), challengeCode: "x".repeat(80), origin: O });
const worstC = shareText({ campaign: mk("WWWWWWWWWWWWWWDDL".slice(0, 16) + "L", { eliminatedIn: "Final" }), challengeCode: "x".repeat(80), origin: O });
const worstD = shareText({ campaign: mk("WDWDWDWDWDWDWDWDL", { eliminatedIn: "Final" }), dailyNumber: 9999, dailyStreak: 9999, origin: O });
const maxLen = Math.max(...xl, ...[worstB, worstC, worstD].map((x) => xLength(x.full)));
console.log(`X length: samples ${xl.join("/")}, worst case ${maxLen} of 280 (margin ${280 - maxLen})`);
t(`every share text <= 160 X chars (max ${maxLen}, margin ${280 - maxLen} to 280)`, maxLen <= 160);
process.exit(fails ? 1 : 0);
